@dataclass(frozen=True)
class RouteActionContract:
    source: str
    route_name: str
    classification: str
    activity_code: str | None
    minimum_level: str | None
    capability_code: str | None
    scope: str
    route_level_derivation: bool = False

    @property
    def key(self):
        return f"{self.source}:{self.route_name}"


@dataclass(frozen=True)
class EnforcementGap:
    code: str
    route_keys: tuple[str, ...]
    description: str
    planned_fix: str


def _activity_routes(
    source,
    names,
    activity_code,
    minimum_level,
    capability_code,
    scope,
    *,
    route_level_derivation=False,
):
    return tuple(
        RouteActionContract(
            source=source,
            route_name=name,
            classification=CLASS_ACTIVITY,
            activity_code=activity_code,
            minimum_level=minimum_level,
            capability_code=capability_code,
            scope=scope,
            route_level_derivation=route_level_derivation,
        )
        for name in names
    )


def _privileged_routes(source, names, capability_code, scope=SCOPE_COMPANY):
    return tuple(
        RouteActionContract(
            source=source,
            route_name=name,
            classification=CLASS_PRIVILEGED,
            activity_code=None,
            minimum_level=None,
            capability_code=capability_code,
            scope=scope,
        )
        for name in names
    )


def _external_routes(source, names):
    return tuple(
        RouteActionContract(
            source=source,
            route_name=name,
            classification=CLASS_EXTERNAL,
            activity_code=None,
            minimum_level=None,
            capability_code=None,
            scope=SCOPE_EXTERNAL,
        )
        for name in names
    )


