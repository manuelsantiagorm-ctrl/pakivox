ROUTE_CONTRACT_BY_KEY = {item.key: item for item in ROUTE_ACTION_CONTRACTS}

def route_action_contract(source, route_name):
    key = f"{source}:{route_name}"
    try:
        return ROUTE_CONTRACT_BY_KEY[key]
    except KeyError as exc:
        raise ValueError(f"Ruta no clasificada en PS-2B: {key}") from exc


def route_keys_for_source(source):
    return frozenset(
        item.key
        for item in ROUTE_ACTION_CONTRACTS
        if item.source == source
    )


