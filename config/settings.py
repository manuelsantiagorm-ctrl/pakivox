def sentry_before_send(event, hint):
    """
    Filtra eventos que son ruido de fondo de internet (bots/escaners
    que mandan Host headers falsos), no errores reales de PAKIVOX.
    """
    exc_info = hint.get("exc_info")
    if exc_info and issubclass(exc_info[0], DisallowedHost):
        return None  # descarta, no lo manda a Sentry
